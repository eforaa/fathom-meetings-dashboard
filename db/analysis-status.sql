-- analysis_status: «в очереди» больше не существует.
--
-- Колонка осталась от ночного разбора, которого давно нет. Каждая новая
-- встреча получала 'pending', и это читалось как очередь, которая вот-вот
-- дойдёт до дела: get_stats честно отдавал «pending: 1027». Очереди нет —
-- встречу разбирает Claude тогда, когда его об этом просят.
--
-- Договорились считать поле так:
--   NULL     — разбор не запрашивали (обычное состояние новой встречи)
--   'done'   — разбор сохранён (save_meeting_analysis)
--   'failed' — пробовали, не вышло
--
-- Код (lib/ingest.js) пишет NULL явно, поэтому он ведёт себя правильно и до
-- применения этого файла. Но пока у колонки стоит DEFAULT 'pending', любая
-- запись мимо ingest снова заведёт «очередь», а развернуть проект с нуля и
-- получить ту же базу нельзя. Этот файл закрывает и то, и другое.
--
-- Безопасно запускать повторно.

-- 1. Новые строки больше не помечаются очередью.
alter table meetings
  alter column analysis_status drop default;

-- 2. Старые пометки очереди снимаются. 'done' и 'failed' не трогаем —
--    это настоящие факты о разборе.
update meetings
   set analysis_status = null
 where analysis_status = 'pending';

