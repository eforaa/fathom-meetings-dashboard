-- Встречи, которые больше никогда не обновятся, помечаются архивом.
--
-- Откуда они взялись. Синхронизация ходит по аккаунтам, у которых есть ключ
-- Fathom. У двух владельцев ключа нет, а встречи от них в базе остались:
--
--   ceo@aivocado.ai          405 встреч
--   d.soloviov@aivocado.ai   383 встречи
--
-- Это 788 из 1111 — почти три четверти базы. Они не сломаны: их можно читать,
-- искать, размечать. Но они застыли: новых конспектов, новых участников и
-- новых полей у них не появится, пока владелец не подключит ключ.
--
-- Отметка archived говорит об этом вслух. Без неё список выглядит так, будто
-- разбор просто не доехал до трёх четвертей встреч, и каждый, кто это увидит,
-- будет заново выяснять, почему.
--
-- Что отметка НЕ делает: не удаляет, не прячет насовсем и не мешает поиску.
-- Приложение по умолчанию показывает живые встречи, а архив открывается одной
-- кнопкой. Подключат ключ — снимаем отметку, и встречи возвращаются в общий
-- поток.
--
-- Безопасно запускать повторно.

-- ---------------------------------------------------------------------------
-- 1. Сама отметка.
-- ---------------------------------------------------------------------------
alter table meetings
  add column if not exists archived boolean not null default false;

-- список открывается фильтром «живые», поэтому индекс по паре владелец+отметка
create index if not exists meetings_owner_archived_idx
  on meetings (owner_email, archived);

-- ---------------------------------------------------------------------------
-- 2. Отметить всё, у чего нет живого ключа.
--
--    Условие описывает правило, а не перечисляет два адреса: появится третий
--    владелец без ключа — тот же запрос отметит и его, а подключит ключ —
--    снимет отметку (см. пункт 3).
-- ---------------------------------------------------------------------------
update meetings
   set archived = true
 where archived = false
   and owner_email not in (select user_email from fathom_accounts);

-- ---------------------------------------------------------------------------
-- 3. И наоборот: у кого ключ есть — тот не архив.
--    Отдельным запросом, чтобы файл можно было запускать после подключения
--    нового ключа и получать верное состояние без ручной правки.
-- ---------------------------------------------------------------------------
update meetings
   set archived = false
 where archived = true
   and owner_email in (select user_email from fathom_accounts);

