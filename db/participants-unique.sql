-- Один участник не должен попадать в одну встречу дважды.
--
-- ВАЖНО: в текущей рабочей базе это ограничение УЖЕ стоит — индекс
-- participants_meeting_identity_key. Но таблица participants создавалась
-- руками, до того как миграции стали лежать в репозитории, поэтому в db/
-- его до сих пор не было: развернуть проект с нуля по этим файлам и получить
-- ту же базу было нельзя. Этот файл закрывает пробел и ничего не меняет там,
-- где индекс уже есть.
--
-- Загрузка (lib/ingest.js) опирается на эту пару: участники пишутся через
-- upsert с onConflict 'meeting_id,identity'. Без индекса upsert не к чему
-- привязать, и postgres ответит ошибкой 42P10.
--
-- Безопасно запускать повторно.

-- ---------------------------------------------------------------------------
-- 1. Сначала убираем дубли, если они где-то уже завелись.
--    Из каждой пары (meeting_id, identity) остаётся одна строка.
-- ---------------------------------------------------------------------------
delete from participants
where id in (
  select id
  from (
    select
      id,
      row_number() over (
        partition by meeting_id, identity
        order by id
      ) as rn
    from participants
    where identity is not null
  ) ranked
  where ranked.rn > 1
);

-- ---------------------------------------------------------------------------
-- 2. Уникальность пары (встреча, участник).
--    identity — генерируемая колонка coalesce(email, name), поэтому ключ
--    строится сам и загрузке передавать его не нужно.
--    Строки с identity is null (ни имени, ни почты) сюда не попадают:
--    в postgres null-ы в уникальном индексе считаются различными.
-- ---------------------------------------------------------------------------
create unique index if not exists participants_meeting_identity_key
  on participants (meeting_id, identity);
