-- ===========================================================================
-- Поиск без расшифровок. Аварийное освобождение места.
--
-- Повод: 13 октября 2026 проект Supabase ушёл в ограниченный режим —
-- exceed_db_size_quota. Перестало работать всё: сайт, коннектор, синхронизация;
-- любой запрос к REST и к Storage отвечал 402.
--
-- Куда ушло место. Колонка search_doc объявлена generated always и включала
-- coalesce(raw_transcript, ''), а поверх неё висел GIN-индекс. То есть каждая
-- расшифровка хранилась трижды: сам текст, его tsvector и индекс поверх
-- tsvector. Расшифровки — самое тяжёлое, что есть в базе (45 МБ на тысячу
-- встреч ещё в августе), и две производные от них стоили больше оригинала.
--
-- Решение принято владельцем: поиском по словам ВНУТРИ расшифровок не
-- пользуются. Значит незачем и платить за него местом. Поиск по названиям и
-- конспектам остаётся и работает так же быстро.
--
-- Расшифровки НЕ удаляются. Они остаются в raw_transcript, их по-прежнему
-- читает коннектор (get_transcript) и разбор встреч. Уходит только индекс.
--
-- ВАЖЕН ПОРЯДОК. На переполненной базе нельзя начинать с перестройки таблицы:
-- для неё нужно свободное место, которого нет. Сначала сносим индекс — он
-- освобождает место сразу и целиком, — потом колонку, потом возвращаем
-- место операционной системе, и только в конце создаём лёгкую замену.
--
-- Выполнять в Supabase → SQL Editor, по шагам, дожидаясь каждого.
-- Безопасно запускать повторно.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- Шаг 0. Разрешить запись в этой сессии.
--
-- На бесплатном тарифе база при превышении 500 МБ переводится в режим «только
-- чтение». Платить за это не обязательно: режим снимается на время одной
-- сессии редактора, и этого хватает, чтобы убрать лишнее.
--
-- Строка действует ТОЛЬКО в текущей вкладке SQL-редактора. Если вкладка
-- закрылась или редактор переподключился — выполнить заново, иначе следующие
-- шаги упадут с ошибкой «read-only transaction».
-- ---------------------------------------------------------------------------
set session characteristics as transaction read write;


-- ---------------------------------------------------------------------------
-- Шаг 1. Снести индекс по расшифровкам.
--
-- Самый большой и самый быстрый выигрыш: файлы индекса удаляются сразу, место
-- возвращается без vacuum. Поиск после этого шага не ломается — код умеет
-- работать и без индекса (проверяет его наличие и откатывается на медленный
-- путь), просто становится медленнее.
-- ---------------------------------------------------------------------------
drop index if exists meetings_search_doc_idx;


-- ---------------------------------------------------------------------------
-- Шаг 2. Убрать саму колонку.
--
-- Postgres помечает её удалённой мгновенно, но место вернёт только шаг 3.
-- ---------------------------------------------------------------------------
alter table meetings
  drop column if exists search_doc;


-- ---------------------------------------------------------------------------
-- Шаг 3. Вернуть освободившееся место операционной системе.
--
-- Без этого шага Supabase по-прежнему считает диск занятым: обычный vacuum
-- помечает место пригодным для повторного использования, но файл не
-- укорачивает. Нужен именно full.
--
-- Предупреждение: vacuum full переписывает таблицу целиком и на время работы
-- требует свободное место размером примерно с саму таблицу. Поэтому он здесь
-- ТРЕТИЙ, а не первый: к этому моменту индекс уже снесён и место под него
-- освобождено. Таблица на время работы заблокирована на запись.
--
-- participants раздувается отдельно: при каждом прогоне синхронизации список
-- участников переписывается upsert-ом, и каждая перезапись оставляет мёртвую
-- строку. Её чистим тем же проходом.
-- ---------------------------------------------------------------------------
vacuum full meetings;
vacuum full participants;


-- ---------------------------------------------------------------------------
-- Шаг 4. Лёгкая замена: тот же поиск, но без расшифровок.
--
-- Названия (все четыре), конспекты (все три) и больше ничего. Разбор 'simple'
-- сохранён намеренно: встречи идут на трёх языках, и любой языковой разбор
-- испортил бы два из них.
--
-- Этот шаг переписывает таблицу — выполнять только после шага 3, когда место
-- уже есть. Если места всё ещё мало, шаг 4 можно отложить: без него поиск
-- работает по медленному пути и ничего не падает.
-- ---------------------------------------------------------------------------
alter table meetings
  add column if not exists search_doc tsvector
  generated always as (
    to_tsvector(
      'simple',
      coalesce(title, '') || ' ' ||
      coalesce(ai_title, '') || ' ' ||
      coalesce(custom_title, '') || ' ' ||
      coalesce(fathom_title, '') || ' ' ||
      coalesce(summary, '') || ' ' ||
      coalesce(custom_summary, '') || ' ' ||
      coalesce(fathom_summary, '')
    )
  ) stored;

create index if not exists meetings_search_doc_idx
  on meetings using gin (search_doc);


