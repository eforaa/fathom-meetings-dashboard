-- Поиск по встречам: индекс вместо чтения всех расшифровок подряд.
--
-- Сейчас поиск идёт через ILIKE '%слово%' по названиям, конспектам и полному
-- тексту расшифровки. Подстроку в середине текста индексом не ускорить, и
-- база честно читает мегабайты на каждый запрос. Замерено на рабочей базе:
--   «клиент»      2805 мс   306 встреч
--   «архитектура» 1520 мс    98 встреч
--   «fathom»      1204 мс   241 встреча
--
-- Здесь добавляется генерируемая колонка со словами всех текстовых полей и
-- GIN-индекс по ней. Слова хранятся конфигурацией 'simple' — без приведения к
-- корню: встречи у нас на трёх языках сразу, и выбрать для них один
-- «русский» или «английский» разбор нельзя, любой выбор портил бы два языка
-- из трёх. Совпадение по началу слова («fath» находит «fathom») код добивает
-- сам, дописывая :* к запросу.
--
-- ВАЖНО: до применения этого файла ничего не сломается. lib/queries.js
-- пробует индекс и, если колонки нет, возвращается к прежнему ILIKE. После
-- применения тот же поиск начинает работать через индекс без правок в коде.
--
-- Безопасно запускать повторно.

-- ---------------------------------------------------------------------------
-- 1. Слова всех полей, по которым ищем, одной колонкой.
--    generated always — postgres пересчитывает её сам при каждой записи,
--    забыть обновить нельзя.
-- ---------------------------------------------------------------------------
alter table meetings
  add column if not exists search_doc tsvector
  generated always as (
    to_tsvector(
      'simple',
      coalesce(title, '') || ' ' ||
      coalesce(ai_title, '') || ' ' ||
      coalesce(custom_title, '') || ' ' ||
      coalesce(fathom_title, '') || ' ' ||
      coalesce(summary, '') || ' ' ||
      coalesce(custom_summary, '') || ' ' ||
      coalesce(fathom_summary, '') || ' ' ||
      coalesce(raw_transcript, '')
    )
  ) stored;

-- ---------------------------------------------------------------------------
-- 2. Индекс. GIN — тот тип, который умеет искать слово внутри документа.
-- ---------------------------------------------------------------------------
create index if not exists meetings_search_doc_idx
  on meetings using gin (search_doc);

-- ---------------------------------------------------------------------------
-- 3. Участники ищутся отдельно и по маленькой таблице, но и там подстрока
--    без индекса. trigram-индекс закрывает ILIKE '%…%' по имени и почте.
--    Расширение уже включено в большинстве проектов Supabase.
-- ---------------------------------------------------------------------------
create extension if not exists pg_trgm;

create index if not exists participants_name_trgm_idx
  on participants using gin (name gin_trgm_ops);

create index if not exists participants_email_trgm_idx
  on participants using gin (email gin_trgm_ops);

