-- Журнал синхронизаций: по строке на каждый запуск сбора встреч.
--
-- Зачем он нужен, если в fathom_accounts уже есть last_synced_at и
-- last_sync_status. Затем, что там хранится ТОЛЬКО последний запуск, и он
-- перезаписывается. По одному последнему значению нельзя ответить на вопросы,
-- которые задают в тот единственный день, когда что-то сломалось:
--
--   • когда сбор в последний раз действительно работал, а не «сейчас упал»;
--   • он падает второй раз подряд или второй месяц подряд;
--   • он вообще запускался вчера — или расписание молча перестало срабатывать
--     (это худший случай: last_synced_at просто застывает, ошибки нет, потому
--     что и запуска не было).
--
-- История отвечает на все три. Одна строка на запуск, ничего не
-- перезаписывается.

create table if not exists sync_runs (
  id uuid primary key default gen_random_uuid(),

  -- чей аккаунт синхронизировали
  user_email text not null,

  -- кто запустил: расписание, кнопка «синхронизировать» или докачка архива
  source text not null check (source in ('cron', 'manual', 'backfill')),

  started_at timestamptz not null default now(),
  finished_at timestamptz,

  -- null означает «запуск начался и не закончился»: страница упала, Vercel
  -- оборвал по таймауту, машина умерла. Такой строки не появилось бы, пиши мы
  -- только по завершении, а именно она и есть след настоящей аварии
  ok boolean,
  error text,

  -- сколько всего получено от Fathom и сколько из этого оказалось новым.
  -- fetched > 0 при inserted = 0 — это нормально (встречи уже были),
  -- а вот fetched = 0 неделю подряд стоит того, чтобы на него посмотреть
  fetched integer,
  inserted integer,
  skipped integer,
  people_refreshed integer,

  -- сколько встреч у аккаунта стало после запуска
  meetings_total integer
);

-- единственный запрос, который к этой таблице ходит: последние N запусков
-- одного аккаунта, свежие сверху
create index if not exists sync_runs_email_started_idx
  on sync_runs (user_email, started_at desc);

