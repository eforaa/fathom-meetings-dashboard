//Резервная копия базы.
//
//До сих пор её не было вообще: 1111 встреч, 45 мегабайт расшифровок и вся
//ручная разметка живут в одном месте. Один неудачный `delete`, один сбой у
//хостинга — и восстанавливать нечего. Это единственный оставшийся риск, у
//которого нет обратного хода.
//
//Здесь только правила, без базы и без сети: как назвать файл, что в него
//класть и какие копии удалять. Проверять надо именно их — особенно последнее:
//чистка, которая ошибётся, сотрёт то, ради чего всё затевалось.

//Сколько копий держим. Семь — это «неделя»: поломку, замеченную в понедельник,
//можно отмотать к прошлому вторнику. Дальше глубина стоит места и почти не
//используется: данные, испорченные две недели назад, всё равно уже разошлись.
export const KEEP = 7;

export const BUCKET = 'backups';

//Имя файла — это дата с точностью до минуты и ничего больше. Такие имена
//сортируются как строки в том же порядке, в каком шло время, поэтому «какие
//удалить» решается сравнением строк, без разбора дат.
export function backupName(nowIso) {
    const at = new Date(nowIso);
    if (Number.isNaN(at.getTime())) throw new Error('backupName: bad date');

    return `${at.toISOString().slice(0, 16).replace(/[:T]/g, '-')}.ndjson.gz`;
}

//Строки лежат по одной в строке (ndjson), а не одним огромным массивом.
//Массив пришлось бы держать в памяти целиком и на обеих сторонах — при чтении
//и при записи; построчный файл читается кусками и переживает обрыв: испорчена
//будет последняя строка, а не весь файл.
export function toNdjson(table, rows) {
    return rows.map((row) => `${JSON.stringify({ table, row })}\n`).join('');
}

//Что НЕ попадает в копию.
//
//Зашифрованный ключ Fathom остаётся в базе и в копию не идёт. Восстановление
//без него обойдётся: человек вставляет ключ заново за минуту. А вот файл с
//ключами — это лишняя поверхность, которая лежит там же, куда попадёт и тот,
//кто однажды доберётся до хранилища.
//
//search_doc — служебная колонка поиска. Она вычисляется самой базой из
//остальных полей и при восстановлении соберётся заново. Замерено: на 200
//встречах она весит 13.8 МБ — столько же, сколько расшифровки. Копировать
//вычислимое, да ещё такой ценой, незачем.
//
//raw_transcript — отдельный разговор, см. WITHOUT_TRANSCRIPTS ниже.
export const SKIP_COLUMNS = {
    fathom_accounts: ['api_key_encrypted'],
    meetings: ['search_doc'],
};

//Расшифровки в ежедневную копию не идут, и это осознанный выбор, а не
//экономия ради экономии.
//
//Их 45 МБ, и запрос за ними не укладывается в минуту, отведённую Vercel:
//проверено, тысяча встреч с расшифровками отваливается по таймауту базы.
//Копия, которая падает через раз, не копия.
//
//Но главное другое: расшифровка — единственное, что можно взять заново.
//Она лежит в Fathom, и повторная синхронизация притащит её обратно. А вот
//то, чего в Fathom нет и не будет, — свои названия, типы, важность, свои
//колонки, склейка людей, конспекты — существует ровно в одном экземпляре,
//и копия делается ради него.
export const WITHOUT_TRANSCRIPTS = { meetings: ['raw_transcript'] };

//полный список колонок, которые не берём из таблицы
export function skipFor(table, { transcripts = false } = {}) {
    const always = SKIP_COLUMNS[table] ?? [];
    if (transcripts) return always;
    return [...always, ...(WITHOUT_TRANSCRIPTS[table] ?? [])];
}

//какие колонки запрашивать: всё, что есть у образца, минус пропускаемые.
//Список строится по живой строке, а не по нашему представлению о схеме —
//колонок в meetings тридцать четыре, и половина появилась мимо миграций
export function columnsToKeep(sampleRow, table, options) {
    const skip = new Set(skipFor(table, options));
    return Object.keys(sampleRow ?? {}).filter((column) => !skip.has(column));
}

//страховка на случай, если колонка всё-таки приехала: запрос строится по
//образцу, а образец берётся из живой базы, и однажды там может оказаться
//что-то, чего мы не ждали
export function stripSecrets(table, row, options) {
    const drop = skipFor(table, options);
    if (!drop.length) return row;

    const clean = { ...row };
    for (const column of drop) delete clean[column];
    return clean;
}

//Какие копии удалить. Возвращает имена, а не количество: пусть вызывающий
//видит, что именно уйдёт.
//
//Правило простое: оставляем KEEP самых свежих, остальное — под нож. Чужие
//файлы, попавшие в то же хранилище, не трогаем вовсе: удалять то, чего мы не
//создавали, — не наше дело.
const OURS = /^\d{4}-\d{2}-\d{2}-\d{2}-\d{2}\.ndjson\.gz$/;

export function expired(names, keep = KEEP) {
    const ours = names.filter((name) => OURS.test(name));
    //свежие сверху: имена сортируются как даты, потому что так и устроены
    const sorted = [...ours].sort().reverse();

    return sorted.slice(keep);
}
