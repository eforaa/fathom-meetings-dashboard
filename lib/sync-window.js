//С какого момента спрашивать у Fathom новые встречи.
//
//Жило внутри ingest.js и потому не проверялось ничем: тот модуль при загрузке
//поднимает клиент базы, и тест падал раньше, чем доходил до правила. Правило
//же простое по виду и неприятное по последствиям — ошибка здесь не ломает
//сбор, а тихо пропускает встречи, и заметить это можно только по их
//отсутствию.

//Насколько отступаем назад от прошлой отметки.
//
//Fathom отдаёт встречи по времени создания, а отметка ставится ДО загрузки.
//Встреча, появившаяся в те же секунды, что и прошлый запуск, оказалась бы
//ровно на границе и могла не попасть ни в тот раз, ни в следующий. Десять
//минут перекрытия делают повтор нормой: повторно скачанная встреча ничего не
//портит (запись идёт upsert-ом), а пропущенная теряется навсегда.
export const OVERLAP_MINUTES = 10;

//Откуда начинать, если аккаунт синхронизируется впервые. Не «с начала времён»:
//INITIAL_SINCE позволяет задать границу, за которой архив тянуть незачем.
export const DEFAULT_SINCE = '2025-01-01T00:00:00Z';

export function lastSyncPoint(account, { initialSince } = {}) {
    if (!account?.lastSyncedAt) {
        return initialSince ?? DEFAULT_SINCE;
    }

    const at = new Date(account.lastSyncedAt).getTime();
    //отметка испорчена — лучше начать с начала, чем передать Fathom «Invalid
    //Date» и получить в ответ неизвестно что
    if (Number.isNaN(at)) return initialSince ?? DEFAULT_SINCE;

    return new Date(at - OVERLAP_MINUTES * 60_000).toISOString();
}
