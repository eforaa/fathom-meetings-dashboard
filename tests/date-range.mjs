// Отбор встреч по датам.
//
// Половина проверок здесь — про часовой пояс. Встречи хранятся моментом
// времени, а живут люди в Киеве, и встреча, начавшаяся в 00:30 по Киеву, по
// UTC приходится на предыдущий день. Отбор, сделанный по UTC, тихо терял бы
// такие встречи: список выглядел бы правдоподобно, просто на одну встречу
// короче.
import {
    dayOf, readRange, inRange, filterByRange, presetRange, rangeShape, rangeLabel,
} from '../lib/date-range.js';
import { check, done } from './_check.mjs';

//--- киевский день ----------------------------------------------------------
check('обычный день', dayOf('2026-08-19T09:00:00Z'), '2026-08-19');
//летом Киев на три часа впереди UTC
check('полпервого ночи по Киеву — это уже следующий день, хотя по UTC ещё нет',
    dayOf('2026-08-18T21:30:00Z'), '2026-08-19');
check('и наоборот: 23:00 по UTC — уже завтра в Киеве',
    dayOf('2026-08-19T23:00:00Z'), '2026-08-20');
//зимой разница два часа — переход на летнее время не должен ничего ломать
check('зимой смещение другое, а правило то же',
    dayOf('2026-01-15T22:30:00Z'), '2026-01-16');
check('без даты дня нет', dayOf(null), null);
check('мусор вместо даты не притворяется днём', dayOf('позавчера'), null);

//--- что пришло в адресе ----------------------------------------------------
check('обе границы приняты',
    readRange({ from: '2026-08-01', to: '2026-08-19' }),
    { from: '2026-08-01', to: '2026-08-19' });
check('одна граница — тоже отбор',
    readRange({ from: '2026-08-01' }), { from: '2026-08-01', to: null });
check('мусор — это «не выбрано», а не ошибка',
    readRange({ from: '19.08.2026', to: 'вчера' }), { from: null, to: null });
check('несуществующий формат отсекается', readRange({ from: '2026-8-1' }).from, null);
//человек ошибся, а не попросил пустой список
check('перепутанные местами концы меняются обратно',
    readRange({ from: '2026-08-19', to: '2026-08-01' }),
    { from: '2026-08-01', to: '2026-08-19' });
check('ничего не пришло — ничего не выбрано', readRange(), { from: null, to: null });

//--- сам отбор --------------------------------------------------------------
const RANGE = { from: '2026-08-10', to: '2026-08-20' };

check('день внутри промежутка проходит', inRange('2026-08-15T09:00:00Z', RANGE), true);
//границы включительно: «с 1 по 31» — это весь месяц
check('первый день промежутка входит в него', inRange('2026-08-10T09:00:00Z', RANGE), true);
check('последний тоже', inRange('2026-08-20T09:00:00Z', RANGE), true);
check('день раньше — мимо', inRange('2026-08-09T09:00:00Z', RANGE), false);
check('день позже — мимо', inRange('2026-08-21T09:00:00Z', RANGE), false);
check('только «с»: всё, что позже, проходит',
    inRange('2026-12-01T09:00:00Z', { from: '2026-08-10' }), true);
check('только «по»: всё, что раньше, проходит',
    inRange('2026-01-01T09:00:00Z', { to: '2026-08-10' }), true);
check('отбора нет — проходит всё', inRange('2020-01-01T09:00:00Z', {}), true);
//встреча без даты не «раньше» и не «позже» — про неё просто ничего не известно
check('встреча без даты выпадает из любого отбора', inRange(null, RANGE), false);
check('но при пустом отборе она остаётся в списке', inRange(null, {}), true);

//граница по Киеву, а не по UTC: эта встреча по UTC 9 августа, по Киеву 10-го
check('встреча в киевскую полночь попадает в киевский день, а не в UTC-вчера',
    inRange('2026-08-09T21:15:00Z', RANGE), true);

const MEETINGS = [
    { id: 'a', date: '2026-08-09T21:15:00Z' },
    { id: 'b', date: '2026-08-15T09:00:00Z' },
    { id: 'c', date: '2026-08-25T09:00:00Z' },
    { id: 'd', date: null },
];

check('отбирается то, что попало', filterByRange(MEETINGS, RANGE).map((m) => m.id), ['a', 'b']);
check('пустой отбор возвращает тот же список целиком',
    filterByRange(MEETINGS, {}).length, MEETINGS.length);
check('исходный список не трогается', MEETINGS.length, 4);

//--- быстрые кнопки ---------------------------------------------------------
//«сейчас» приходит аргументом, иначе проверить можно было бы только сегодня
const NOW = '2026-08-19T09:00:00Z';

check('сегодня — это один день', presetRange('today', NOW), { from: '2026-08-19', to: '2026-08-19' });
//неделя включает оба конца: сегодня и шесть предыдущих дней
check('семь дней', presetRange('week', NOW), { from: '2026-08-13', to: '2026-08-19' });
check('тридцать дней', presetRange('month', NOW), { from: '2026-07-21', to: '2026-08-19' });
check('этот месяц — с первого числа', presetRange('thisMonth', NOW),
    { from: '2026-08-01', to: '2026-08-19' });
check('неизвестная кнопка ничего не выбирает', presetRange('когда-нибудь', NOW),
    { from: null, to: null });
//переход через начало месяца не должен давать «2026-08-00»
check('семь дней от первого числа уходят в прошлый месяц',
    presetRange('week', '2026-08-02T09:00:00Z').from, '2026-07-27');
check('и через начало года тоже',
    presetRange('week', '2026-01-02T09:00:00Z').from, '2025-12-27');

//--- что написать на кнопке -------------------------------------------------
check('отбора нет', rangeShape({}).kind, 'any');
check('один день', rangeShape({ from: '2026-08-19', to: '2026-08-19' }).kind, 'day');
check('промежуток', rangeShape({ from: '2026-08-01', to: '2026-08-19' }).kind, 'between');
check('только начало', rangeShape({ from: '2026-08-01' }).kind, 'since');
check('только конец', rangeShape({ to: '2026-08-19' }).kind, 'until');

//--- подпись отбора ---------------------------------------------------------
//
//Её читают в двух местах: на самой кнопке и в строке свёрнутой панели
//сортировки. Пока строка собиралась в кнопке, второго читателя не было; теперь
//есть, и разойтись они не должны.
//
//Словарь здесь ненастоящий — проверяется склейка, а не перевод.
const T = (key) => ({ 'dates.any': 'Усі дати', 'dates.sinceShort': 'з', 'dates.untilShort': 'по' })[key];

check('без отбора — так и сказано словами', rangeLabel({}, T), 'Усі дати');
check('один день — число и месяц, без года',
    rangeLabel({ from: '2026-08-19', to: '2026-08-19' }, T), '19.08');
check('промежуток — оба конца',
    rangeLabel({ from: '2026-08-01', to: '2026-08-19' }, T), '01.08 — 19.08');
check('только начало', rangeLabel({ from: '2026-08-01' }, T), 'з 01.08');
check('только конец', rangeLabel({ to: '2026-08-19' }, T), 'по 19.08');
//перевёрнутые концы поправляет readRange, и подпись обязана показывать
//исправленное, а не то, что пришло
check('перепутанные местами концы читаются в правильном порядке',
    rangeLabel(readRange({ from: '2026-08-19', to: '2026-08-01' }), T), '01.08 — 19.08');

done();
