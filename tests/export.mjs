// Выгрузка списка в файл.
//
// Почти вся боль выгрузки живёт в экранировании, и ломается оно тихо: файл
// открывается, просто колонки в одной строке съехали. Конспект встречи полон
// запятых, кавычек и переносов строк, в имени бывает запятая перед фамилией,
// а в названии — вертикальная черта, которая для Markdown разделитель колонок.
import { csvCell, toCsv, mdCell, toMarkdown, fileName } from '../lib/export.js';
import { check, done } from './_check.mjs';

//--- CSV: одна ячейка -------------------------------------------------------
check('обычное слово остаётся как есть', csvCell('Синхрон'), 'Синхрон');
check('запятая заставляет взять поле в кавычки',
    csvCell('Иванов, Пётр'), '"Иванов, Пётр"');
//кавычка внутри удваивается — правило старше нас всех (RFC 4180)
check('кавычка удваивается', csvCell('тема «X» и "Y"'), '"тема «X» и ""Y"""');
check('перенос строки прячется в кавычки',
    csvCell('первая\nвторая'), '"первая\nвторая"');
check('точка с запятой тоже: в русской раскладке Excel разделитель именно она',
    csvCell('раз;два'), '"раз;два"');
check('пусто — это пустое поле, а не слово null', csvCell(null), '');
check('ноль — это ноль, а не пустота', csvCell(0), '0');

//--- CSV: таблица целиком ---------------------------------------------------
const COLUMNS = [
    { title: 'Дата', value: (r) => r.date },
    { title: 'Встреча', value: (r) => r.title },
    { title: 'Важность', value: (r) => r.importance, numeric: true },
];

const ROWS = [
    { date: '19.08.2026', title: 'Планёрка', importance: 3 },
    { date: '18.08.2026', title: 'Разговор с "Ромашкой", часть 2', importance: 0 },
];

const csv = toCsv(ROWS, COLUMNS);

//без метки в начале Excel открывает кириллицу кракозябрами, и человек решает,
//что выгрузка сломана
check('файл начинается с метки UTF-8', csv.charCodeAt(0), 0xfeff);
check('шапка на месте', csv.split('\r\n')[0], '\ufeffДата,Встреча,Важность');
check('опасная строка целиком в кавычках',
    csv.split('\r\n')[2], '18.08.2026,"Разговор с ""Ромашкой"", часть 2",0');
//CR+LF, а не одиночный перевод: Excel на Windows читает одиночный как конец записи
check('строки разделены парой CR+LF', csv.includes('\r\n'), true);
check('файл заканчивается переводом строки', csv.endsWith('\r\n'), true);
check('строк ровно столько, сколько встреч, плюс шапка',
    csv.trimEnd().split('\r\n').length, ROWS.length + 1);
check('пустой список — это шапка и ничего больше',
    toCsv([], COLUMNS).trimEnd().split('\r\n').length, 1);

//--- Markdown ---------------------------------------------------------------
check('вертикальная черта экранируется — иначе она разорвала бы строку',
    mdCell('до | после'), 'до \\| после');
check('обратная косая тоже', mdCell('C:\\путь'), 'C:\\\\путь');
//строка таблицы в Markdown — одна строка текста, перенос разорвал бы её
check('перенос строки превращается в пробел', mdCell('первая\nвторая'), 'первая вторая');
check('пусто — пустая ячейка', mdCell(null), '');

const md = toMarkdown(ROWS, COLUMNS, { title: 'Встречи за август' });
const lines = md.split('\n');

check('заголовок сверху', lines[0], '# Встречи за август');
check('шапка таблицы', lines[2], '| Дата | Встреча | Важность |');
//двоеточие справа прижимает числа к правому краю
check('числовая колонка выровнена по правому краю', lines[3], '| --- | --- | ---: |');
check('строка встречи', lines[4], '| 19.08.2026 | Планёрка | 3 |');
check('без заголовка таблица начинается сразу',
    toMarkdown(ROWS, COLUMNS).split('\n')[0], '| Дата | Встреча | Важность |');

//Настоящее свойство таблицы Markdown: в каждой строке ровно столько
//неэкранированных разделителей, сколько колонок, плюс один. Именно оно
//ломается от черты внутри названия — и ломается тихо, съезжают колонки.
function bars(line) {
    let count = 0;
    for (let i = 0; i < line.length; i += 1) {
        if (line[i] !== '|') continue;
        //черта, перед которой стоит нечётное число косых, экранирована
        let slashes = 0;
        for (let j = i - 1; j >= 0 && line[j] === '\\'; j -= 1) slashes += 1;
        if (slashes % 2 === 0) count += 1;
    }
    return count;
}

const TRICKY = [
    { date: '19.08.2026', title: 'Отчёт | сводка', importance: 5 },
    { date: '18.08.2026', title: 'Путь C:\\счета\\', importance: 1 },
    { date: '17.08.2026', title: 'Две\nстроки', importance: 2 },
];

const rowsOf = (text) => text.split('\n').filter((line) => line.startsWith('|'));

check('черта в названии не добавляет колонку',
    rowsOf(toMarkdown(TRICKY, COLUMNS)).every((line) => bars(line) === COLUMNS.length + 1), true);
check('строк ровно столько, сколько встреч, плюс шапка и линейка',
    rowsOf(toMarkdown(TRICKY, COLUMNS)).length, TRICKY.length + 2);
check('перенос строки не разрывает строку таблицы',
    rowsOf(toMarkdown(TRICKY, COLUMNS)).length, TRICKY.length + 2);

//--- имя файла --------------------------------------------------------------
//через месяц в папке загрузок «meetings.csv» ничего не объяснит
check('промежуток дат попадает в имя',
    fileName({ from: '2026-08-01', to: '2026-08-19', format: 'csv' }),
    'meetings-2026-08-01_2026-08-19.csv');
check('один день — одна дата', fileName({ from: '2026-08-19', to: '2026-08-19', format: 'csv' }),
    'meetings-2026-08-19.csv');
check('только начало', fileName({ from: '2026-08-01', format: 'md' }), 'meetings-from-2026-08-01.md');
check('только конец', fileName({ to: '2026-08-19', format: 'md' }), 'meetings-to-2026-08-19.md');
check('без отбора — день выгрузки', fileName({ stamp: '2026-08-20', format: 'csv' }),
    'meetings-2026-08-20.csv');
check('расширение по формату', fileName({ stamp: '2026-08-20', format: 'md' }),
    'meetings-2026-08-20.md');

done();
