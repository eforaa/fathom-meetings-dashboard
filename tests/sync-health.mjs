// «А сбор вообще работает?»
//
// На этот вопрос до сих пор нельзя было ответить: в базе лежал только
// результат последнего запуска, и он перезаписывался. Самая неприятная поломка
// не оставляла следов вовсе — расписание молча перестаёт срабатывать, ошибки
// нет, потому что и запуска не было, а last_synced_at просто застывает.
//
// Здесь проверяется функция, которая эту тишину и ловит. Времени «сейчас» она
// не берёт сама — оно приходит аргументом, поэтому день, час и минуту можно
// назначить любые.
import { syncHealth, ago, quietFor } from '../lib/sync-health.js';
import { check, done } from './_check.mjs';

//сбор ходит раз в сутки в 17:00 UTC
const RAN = '2026-08-19T17:00:00Z';
const level = (now, lastStatus = 'ok', lastSyncedAt = RAN) =>
    syncHealth({ lastSyncedAt, lastStatus, now }).level;

//--- обычная жизнь ----------------------------------------------------------
check('через час после запуска всё хорошо', level('2026-08-19T18:00:00Z'), 'ok');
check('через сутки, прямо перед следующим запуском, всё ещё хорошо',
    level('2026-08-20T16:55:00Z'), 'ok');

//запас в два часа: без него «здоров» превращался бы в «опоздал» каждый вечер
//из-за нескольких минут разницы в расписании
check('опоздание на час — ещё не опоздание', level('2026-08-20T18:00:00Z'), 'ok');

//--- пропуски ---------------------------------------------------------------
check('пропустили один запуск — опоздание', level('2026-08-20T21:00:00Z'), 'late');
check('пропустили два — сбор стоит', level('2026-08-21T21:00:00Z'), 'stale');
check('неделя тишины — по-прежнему стоит, но пропусков видно шесть',
    syncHealth({ lastSyncedAt: RAN, lastStatus: 'ok', now: '2026-08-26T17:00:00Z' }).missed, 6);

//--- ошибки -----------------------------------------------------------------
//падающий сбор — это НЕ то же самое, что остановившийся: он приходит вовремя
//и каждый раз ломается. Лечится по-разному, значит и называться должно
//по-разному
check('последний запуск упал — это отдельное состояние',
    level('2026-08-19T18:00:00Z', 'failed'), 'failing');
check('упал и с тех пор не приходил — всё равно «падает», это важнее давности',
    level('2026-08-25T18:00:00Z', 'failed'), 'failing');

//--- край ---------------------------------------------------------------------
check('ключ подключили, сбор ещё ни разу не доходил до конца',
    level('2026-08-19T18:00:00Z', null, null), 'never');
check('мусор вместо даты не выдаётся за рабочее состояние',
    level('2026-08-19T18:00:00Z', 'ok', 'позавчера'), 'never');
check('время из будущего не даёт отрицательной давности',
    syncHealth({ lastSyncedAt: '2026-08-21T00:00:00Z', lastStatus: 'ok', now: RAN }).hoursAgo, 0);

//--- как это произносится ---------------------------------------------------
//число и единица, а не готовая фраза: слова живут в словаре, иначе они не
//переведутся на три языка
check('меньше часа считается в минутах', ago(0.5), { value: 30, unit: 'minute' });
check('«только что» — это всё-таки одна минута, а не ноль', ago(0.001), { value: 1, unit: 'minute' });
check('часы', ago(5), { value: 5, unit: 'hour' });
check('от суток считаем днями', ago(50), { value: 2, unit: 'day' });
check('без даты сказать нечего', ago(null), null);

//--- тишина при полном порядке ----------------------------------------------
//запуски проходят, ошибок нет, но не приносят ничего. Само по себе нормально —
//неделя без встреч бывает, — поэтому это не тревога, а факт рядом
const run = (ok, fetched) => ({ ok, fetched });

check('последний запуск принёс встречи — тишины нет',
    quietFor([run(true, 3), run(true, 0), run(true, 0)]), 0);
check('три пустых подряд', quietFor([run(true, 0), run(true, 0), run(true, 0)]), 3);
check('счёт прерывается на первом непустом',
    quietFor([run(true, 0), run(true, 5), run(true, 0)]), 1);

//упавший запуск пуст по другой причине, и мешать эти два случая нельзя:
//иначе «сломан ключ» читалось бы как «встреч не было»
check('упавшие запуски в счёт тишины не идут',
    quietFor([run(false, null), run(true, 4)]), 0);
check('истории нет — и тишины нет', quietFor([]), 0);

done();
