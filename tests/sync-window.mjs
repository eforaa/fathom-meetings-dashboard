// С какого момента спрашивать у Fathom новые встречи.
//
// Правило жило внутри ingest.js и не проверялось ничем: тот модуль при
// загрузке поднимает клиент базы, и тест падал раньше, чем доходил до правила.
// Теперь оно вынесено отдельно — и вот что важно проверить: ошибка здесь не
// ломает сбор, она тихо пропускает встречи. Заметить это можно только по их
// отсутствию, то есть, скорее всего, никогда.
import { lastSyncPoint, OVERLAP_MINUTES, DEFAULT_SINCE } from '../lib/sync-window.js';
import { check, done } from './_check.mjs';

const LAST = '2026-08-19T17:41:00.000Z';

//--- перекрытие -------------------------------------------------------------
//Отметка ставится ДО загрузки, а Fathom отдаёт встречи по времени создания.
//Встреча, появившаяся в те же секунды, оказалась бы ровно на границе и могла
//не попасть ни в этот запуск, ни в следующий. Поэтому спрашиваем чуть раньше:
//повторно скачанная встреча ничего не портит (запись идёт upsert-ом),
//пропущенная теряется навсегда.
check('спрашиваем раньше прошлой отметки',
    lastSyncPoint({ lastSyncedAt: LAST }), '2026-08-19T17:31:00.000Z');
check('ровно на величину перекрытия',
    (new Date(LAST) - new Date(lastSyncPoint({ lastSyncedAt: LAST }))) / 60000,
    OVERLAP_MINUTES);
check('перекрытие направлено назад, а не вперёд',
    lastSyncPoint({ lastSyncedAt: LAST }) < LAST, true);

//граница суток: отступ назад не должен ломать дату
check('через полночь отступ уходит во вчера',
    lastSyncPoint({ lastSyncedAt: '2026-08-20T00:05:00.000Z' }), '2026-08-19T23:55:00.000Z');
check('через начало года — в прошлый год',
    lastSyncPoint({ lastSyncedAt: '2026-01-01T00:05:00.000Z' }), '2025-12-31T23:55:00.000Z');
check('ответ всегда в UTC с Z на конце',
    lastSyncPoint({ lastSyncedAt: LAST }).endsWith('Z'), true);

//--- первый заход -----------------------------------------------------------
check('аккаунт без отметки начинает с общей границы',
    lastSyncPoint({}), DEFAULT_SINCE);
check('и пустая отметка считается её отсутствием',
    lastSyncPoint({ lastSyncedAt: null }), DEFAULT_SINCE);
check('вместо аккаунта пришло ничего — тоже общая граница',
    lastSyncPoint(undefined), DEFAULT_SINCE);
//INITIAL_SINCE позволяет не тянуть архив глубже нужного
check('заданная граница перебивает общую',
    lastSyncPoint({}, { initialSince: '2026-01-01T00:00:00Z' }), '2026-01-01T00:00:00Z');
check('но у аккаунта с отметкой она не спрашивается',
    lastSyncPoint({ lastSyncedAt: LAST }, { initialSince: '2026-01-01T00:00:00Z' }),
    '2026-08-19T17:31:00.000Z');

//--- испорченная отметка ----------------------------------------------------
//«Invalid Date», переданная в Fathom, вернула бы неизвестно что: молчаливую
//пустоту или всю историю разом. Лучше честно начать с начала
check('мусор вместо даты не превращается в Invalid Date',
    lastSyncPoint({ lastSyncedAt: 'позавчера' }), DEFAULT_SINCE);
check('и число вместо даты тоже',
    lastSyncPoint({ lastSyncedAt: {} }), DEFAULT_SINCE);

done();
